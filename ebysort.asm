.MODEL SMALL
.DATA
LIST DB 2h, 9h, 8h, 5h, 3h
.CODE
MOV AX, @DATA
MOV DS, AX


MOV CL,05h
L1: MOV CH, 05h
MOV SI, OFFSET LIST
L2: MOV AL, [SI]
INC SI
CMP AL, [SI]
JC SKIP
XCHG AL,[SI]
DEC SI
XCHG AL, [SI]
INC SI
SKIP: DEC CH
JNZ L2
DEC CL
JNZ L1

MOV CX, 05H
MOV SI, OFFSET LIST
L3: MOV AL,[SI]
CMP AL,0Ah
JGE ALPHA
ADD AL,30h
JMP INCRE
ALPHA: ADD AL,37h
INCRE: MOV DL,AL
MOV AH,02H
INT 21H
INC SI 
LOOP L3
MOV AH,4Ch
INT 21h
END
